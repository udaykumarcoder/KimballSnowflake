-- TASK 1 — CREATE DATABASE AND SCHEMA CONTEXT

CREATE DATABASE RETAIL_SCHEMAS_DW;

USE DATABASE RETAIL_SCHEMAS_DW;

CREATE SCHEMA SCHEMA_COMPARISON;

USE SCHEMA SCHEMA_COMPARISON;

